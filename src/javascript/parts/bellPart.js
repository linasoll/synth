function shiftBellPart(part, startMeasure) {
    return part.map(note => {
        const [measure, beat, sixteenth] = note.time.split(":").map(Number)

        return {
        ...note,
        time: `${measure + startMeasure}:${beat}:${sixteenth}`
        }
    })
}


